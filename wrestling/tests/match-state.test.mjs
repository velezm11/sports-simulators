import assert from "node:assert/strict";
import {createMatch,applyTransition,resetMatch} from "../v2/match-state.js";
let m=createMatch();
assert.deepEqual(m,{red:0,green:0,state:"neutral",history:[]});
m=applyTransition(m,"red-control");
assert.equal(m.red,3); assert.equal(m.green,0); assert.equal(m.history.at(-1).call,"takedown");
m=applyTransition(m,"neutral");
assert.equal(m.green,1); assert.equal(m.history.at(-1).call,"escape");
m=applyTransition(m,"green-control");
assert.equal(m.green,4); assert.equal(m.history.at(-1).call,"takedown");
m=applyTransition(m,"red-control");
assert.equal(m.red,5); assert.equal(m.history.at(-1).call,"reversal");
const before=m.history.length; m=applyTransition(m,"red-control"); assert.equal(m.history.length,before);
assert.deepEqual(resetMatch(),{red:0,green:0,state:"neutral",history:[]});
console.log("PASS: wrestling match-state regression");
